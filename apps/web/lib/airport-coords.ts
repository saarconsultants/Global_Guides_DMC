/** Resolve a city or airport code to the airport actually used. */
export function resolveAirportCode(code: string): string {
  const c = (code ?? '').toUpperCase();
  return CITY_AIRPORT_OVERRIDES[c] ?? c;
}

/** Address + coordinates for an airport, or null when we have no verified coordinates. */
export function airportPlace(code: string): { address: string; latitude: number; longitude: number } | null {
  const a = AIRPORT_COORDS[resolveAirportCode(code)];
  return a ? { address: a.name, latitude: a.lat, longitude: a.lng } : null;
}
